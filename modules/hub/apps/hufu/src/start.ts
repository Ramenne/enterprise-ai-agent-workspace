import {installControlInbox} from '../../../packages/control-inbox/src/http.mjs';
import {installProjectMembers} from '../../../packages/project-members/src/http.mjs';
import {installSqliteDatabaseAccess} from '../../../packages/sqlite-database-access/src/http.mjs';
import {installNativeVaultEntryClaims} from '../../../packages/native-vault-claims/src/http.mjs';
import {installAssetBackups} from '../../../packages/asset-backups/src/asset-api.mjs';
import {installProjectBackups} from '../../../packages/project-backups/src/http.mjs';
import {installApplicationDevices} from '../../../packages/legacy-application-grants/src/devices.mjs';
import {installLegacyApplicationGrants} from '../../../packages/legacy-application-grants/src/http.mjs';
import {installResourceProjects} from '../../../packages/shared-resources/src/http.mjs';
import {installAuthorization} from '../../../packages/authorization/src/authorization.mjs';
import {installDatabaseAccess} from '../../../packages/database-access/src/database-access.mjs';
import {installEngineering} from '../../../packages/engineering/src/engineering.mjs';
import {installOfficialManuals} from '../../../packages/handbook/src/http.mjs';
import {installRuntimeSources} from '../../../packages/runtime-sources/src/runtime-source.mjs';
import {sqlFunction} from '../../../packages/platform/src/db.js';
import{closeUsage,usageStatus}from'../../../packages/platform/src/usage.js';
import {installVaultNext} from '../../../packages/vault/next/src/runtime.mjs';
import {verificationMailGateway,otpMailGateway} from '../../../packages/member-auth/src/mail.mjs';
import {database} from '../../../packages/platform/src/db.js';
import {run,DomainError} from '../../../packages/platform/src/http.js';
import {wechatProvider} from './wechat.js';
import {createMemberAuth} from './auth.js';
import {createServer} from './server.js';
import {loadRuntime} from '../../../packages/platform/src/runtime.js';
import {installDatabaseReadiness} from '../../../packages/platform/src/readiness.js';
import {createVaultService} from '../../../packages/vault/src/service.mjs';
import {installVaultRoutes} from '../../../packages/vault/src/http.mjs';
const runtime=await loadRuntime('hufu');
const databaseUrl=runtime.optional('database_url','DATABASE_URL')??'';
const pool=await runtime.databasePool('DATABASE_URL');
const usagePool=await runtime.databasePool('DATABASE_URL',{max:1});const usageSpoolDirectory='/srv/workspace';
const serviceKeys={mem:runtime.required('mem_service_key','HUFU_MEM_SERVICE_KEY'),v8:runtime.required('v8_service_key','HUFU_V8_SERVICE_KEY'),worker:runtime.required('worker_service_key','HUFU_WORKER_SERVICE_KEY')};
if(new Set(Object.values(serviceKeys)).size!==3) throw new Error('independent audience service keys required');
const authUrl=process.env['BETTER_AUTH_URL']??'http://127.0.0.1:4611';
const verificationMailUrl=runtime.optional('verification_mail_url','HUFU_VERIFICATION_MAIL_URL');
const verificationMailToken=runtime.optional('verification_mail_token','HUFU_VERIFICATION_MAIL_TOKEN');
if(Boolean(verificationMailUrl)!==Boolean(verificationMailToken))throw new Error('verification_mail_gateway_pair_required');
const otpMailUrl=runtime.optional('email_otp_mail_url','HUFU_EMAIL_OTP_MAIL_URL');
const otpMailToken=runtime.optional('email_otp_mail_token','HUFU_EMAIL_OTP_MAIL_TOKEN');
if(Boolean(otpMailUrl)!==Boolean(otpMailToken))throw new Error('email_otp_mail_gateway_pair_required');
const appId=runtime.optional('wechat_app_id','WECHAT_APP_ID');
const wechat=appId?{appId,provider:wechatProvider({appId,appSecret:runtime.required('wechat_app_secret','WECHAT_APP_SECRET'),redirectUri:runtime.required('wechat_redirect_uri','WECHAT_REDIRECT_URI')})}:undefined;
if(appId&&process.env['HUFU_STANDARD_MEMBER_AUTH']==='enabled'&&runtime.required('wechat_redirect_uri','WECHAT_REDIRECT_URI')!==authUrl.replace(/\/$/,'')+'/v2/auth/sign-in/wechat/callback')throw new Error('wechat_standard_callback_mismatch');
const standard=process.env['HUFU_STANDARD_MEMBER_AUTH']==='enabled'?{...(otpMailUrl&&otpMailToken?{sendVerificationOTP:otpMailGateway(otpMailUrl,otpMailToken)}:{}),...(wechat?{wechat}:{}),resource:process.env['HUFU_MCP_OAUTH_RESOURCE']??runtime.required('mcp_oauth_resource','HUFU_MCP_OAUTH_RESOURCE'),...(verificationMailUrl&&verificationMailToken?{sendVerificationEmail:verificationMailGateway(verificationMailUrl,verificationMailToken)}:{})}:undefined;
const memberAuth=createMemberAuth(await runtime.databasePool('DATABASE_URL',{options:'-c search_path=authn,pg_catalog',max:4}),authUrl,runtime.required('auth_secret','BETTER_AUTH_SECRET'),standard);
const resourceExecutionKey=runtime.optional('resource_execution_key','HUFU_RESOURCE_EXECUTION_KEY');
const managementRelay=runtime.optional('provider_management_relay','HUFU_PROVIDER_MANAGEMENT_RELAY');
const app=createServer({...(managementRelay?{providerManagementRelay:JSON.parse(managementRelay)}:{}),pool,usagePool,usageSpoolDirectory,serviceKeys,...(resourceExecutionKey?{resourceExecutionKey}:{}),credentialKey:runtime.required('credential_key','HUFU_CREDENTIAL_KEY'),memberAuth,...(wechat?{wechat}:{})});
installRuntimeSources(app,{DomainError,sql:(name:string,args:unknown[])=>sqlFunction(pool,name,args)});
const vaultNext=await installVaultNext(app,pool,runtime,installVaultRoutes);
installNativeVaultEntryClaims(app,{pool,runtime,vaultNext});
installOfficialManuals(app,pool);
installEngineering(app,{pool,runtime,memberAuth});
installProjectMembers(app,{pool});
installControlInbox(app,{pool});
installAuthorization(app,{pool,credentialKey:runtime.required('credential_key','HUFU_CREDENTIAL_KEY')});
installDatabaseAccess(app,{pool});
installSqliteDatabaseAccess(app,{pool,runtime});
await installResourceProjects(app,{pool,runtime});
installLegacyApplicationGrants(app,{pool});
installApplicationDevices(app,{pool});
installProjectBackups(app,{pool,serviceKey:runtime.required('resource_execution_key','HUFU_RESOURCE_EXECUTION_KEY')});
installAssetBackups(app,{pool,serviceKey:runtime.required('resource_execution_key','HUFU_RESOURCE_EXECUTION_KEY')});
installDatabaseReadiness(app,pool,{wechat:wechat?'configured_not_live_verified':'configuration_required',secrets:runtime.mode},()=>({usage:usageStatus(app)}));
app.addHook('onClose',async()=>{await closeUsage(app);await usagePool.end();await memberAuth.pool.end();await pool.end();await runtime.close();});
await run(app,Number(process.env['PORT']??'4611'));
